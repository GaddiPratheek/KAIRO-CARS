export const ALL_BRAND_NAMES = LUXURY_BRANDS_CATALOG.map((b) => b.name);

export function getModelsForBrand(brandName: string): string[] {
  if (!brandName || brandName === 'All') {
    return LUXURY_BRANDS_CATALOG.flatMap((b) => b.models);
  }
  const found = LUXURY_BRANDS_CATALOG.find(
    (b) => b.name.toLowerCase() === brandName.toLowerCase()
  );
  return found ? found.models : [];
}
